from datetime import datetime
from pathlib import Path


def generate_report(context, analysis, risk_assessment=None):
    """
    Generate the final SOC incident report.

    The deterministic risk engine remains the source
    of truth for severity.
    """

    current_time = datetime.now()

    severity = (
        risk_assessment.get("level", "UNKNOWN")
        if risk_assessment
        else "UNKNOWN"
    )

    return f"""# 🛡️ AI SOC INCIDENT REPORT

**Incident ID:** IR-{current_time.strftime("%Y%m%d-%H%M%S")}

**Generated:** {current_time.strftime("%d %B %Y, %I:%M:%S %p")}

**Severity:** {severity}

---

# 📋 Incident Context

{context}

---

# 🤖 AI SOC Analysis

{analysis}

---

# 📌 Report Information

- Generated by: **AI SOC Assistant**
- Report Format: Markdown (.md)
- Analysis Engine: **OpenRouter LLM**
"""


def save_report(report):
    """
    Save the generated incident report inside the reports directory.
    """

    reports_folder = Path("reports")
    reports_folder.mkdir(parents=True, exist_ok=True)

    filename = (
        f"Incident_Report_"
        f"{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
    )

    filepath = reports_folder / filename
    filepath.write_text(report, encoding="utf-8")

    return filepath